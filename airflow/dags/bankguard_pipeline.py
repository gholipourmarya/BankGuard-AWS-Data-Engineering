"""BankGuard orchestration: check inputs -> run Glue job -> verify outputs -> Athena query.

Optional extension: the pipeline also works without Airflow (start the Glue job
from the console, CLI or GitHub Actions). A complete DAG run succeeded on
MWAA with Airflow 3.3.1 on 2026-10-28; see docs/evidence/2026-10-28/.

Configuration, in this order:
    1. ``bankguard_config.py`` next to the DAG. Terraform generates it when MWAA is enabled
       (enable_mwaa = true), so nothing has to be set by hand.
    2. Airflow Variables (Admin > Variables) for a self-hosted Airflow:
       bankguard_bucket, bankguard_glue_job (default bankguard-etl), bankguard_workgroup (default bankguard)
On MWAA the execution role provides AWS access; self-hosted Airflow needs the
connection ``aws_default`` with credentials that may run Glue jobs, read the
bucket and run Athena queries.

Includes import fallbacks for Airflow 2; only Airflow 3.3.1 is verified on MWAA.
"""
from datetime import datetime, timedelta
import json

from airflow import DAG
from airflow.models import Variable

try:  # Airflow 3
    from airflow.providers.standard.operators.python import PythonOperator
except ImportError:  # Airflow 2
    from airflow.operators.python import PythonOperator

try:
    from airflow.exceptions import AirflowFailException
except ImportError:  # Airflow 3 moved it
    from airflow.sdk.exceptions import AirflowFailException

from airflow.providers.amazon.aws.hooks.s3 import S3Hook
from airflow.providers.amazon.aws.operators.athena import AthenaOperator
from airflow.providers.amazon.aws.operators.glue import GlueJobOperator
from airflow.providers.amazon.aws.sensors.s3 import S3KeySensor

try:
    from bankguard_validation import validate_metrics  # Terraform uploads src/validate.py under this name.
except ModuleNotFoundError as exc:
    if exc.name != "bankguard_validation":
        raise
    from src.validate import validate_metrics  # Local development from the repository.

try:
    from bankguard_config import BUCKET, GLUE_JOB, WORKGROUP, DATABASE  # generated by Terraform for MWAA
except ImportError:
    BUCKET = Variable.get("bankguard_bucket", default_var="")
    GLUE_JOB = Variable.get("bankguard_glue_job", default_var="bankguard-etl")
    WORKGROUP = Variable.get("bankguard_workgroup", default_var="bankguard")
    DATABASE = Variable.get("bankguard_database", default_var="bankguard")

RAW_FILES = ["raw/customers.csv", "raw/accounts.csv", "raw/transactions.csv"]


def verify_outputs(ti):
    """Verify this Glue run's success receipt, including valid zero-row results."""
    run_id = ti.xcom_pull(task_ids="start_glue_job")
    if not run_id:
        raise AirflowFailException("Glue did not return a run ID")
    hook = S3Hook(aws_conn_id="aws_default")
    metrics = json.loads(hook.read_key(key=f"runs/{run_id}/metrics.json", bucket_name=BUCKET))
    if not isinstance(metrics, dict) or metrics.get("run_id") != run_id:
        raise AirflowFailException("Glue run receipt is missing or inconsistent")
    try:
        validate_metrics(metrics)
    except ValueError as exc:
        raise AirflowFailException(f"Glue run receipt is inconsistent: {exc}") from exc
    if metrics.get("database") != f"{DATABASE}_{run_id}":
        raise AirflowFailException("Glue receipt does not identify this run's snapshot database")
    print(json.dumps(metrics, sort_keys=True))
    return metrics


with DAG(
    dag_id="bankguard_pipeline",
    description="Validate banking CSV data with AWS Glue and report with Athena",
    start_date=datetime(2026, 10, 1),
    schedule=None,  # manual trigger; use "@daily" to run on a schedule
    catchup=False,
    default_args={"retries": 1, "retry_delay": timedelta(minutes=5),
                  "execution_timeout": timedelta(minutes=60)},
    tags=["bankguard"],
) as dag:

    check_inputs = S3KeySensor(
        task_id="check_inputs",
        bucket_name=BUCKET,
        bucket_key=RAW_FILES,
        aws_conn_id="aws_default",
        poke_interval=30,
        timeout=15 * 60,
    )

    # wait_for_completion=True makes this task finish only when the Glue run has ended;
    # the task fails if the run FAILED, TIMEOUT or ERROR.
    start_glue_job = GlueJobOperator(
        task_id="start_glue_job",
        job_name=GLUE_JOB,
        wait_for_completion=True,
        aws_conn_id="aws_default",
    )

    verify = PythonOperator(task_id="verify_outputs", python_callable=verify_outputs)

    run_athena_query = AthenaOperator(
        task_id="run_athena_query",
        query="""
            SELECT transaction_date, currency, COUNT(*) AS transaction_count, SUM(amount) AS total_amount
            FROM curated_transactions
            GROUP BY transaction_date, currency
            ORDER BY transaction_date, currency
            LIMIT 20
        """,
        database="{{ ti.xcom_pull(task_ids='verify_outputs')['database'] }}",
        output_location=f"s3://{BUCKET}/athena-results/",
        workgroup=WORKGROUP,
        aws_conn_id="aws_default",
    )

    check_inputs >> start_glue_job >> verify >> run_athena_query
